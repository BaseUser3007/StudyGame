/// <summary>
/// Выход из забега через портал (реализует RunController). Lua-команда входа в портал получает его
/// через интерфейс, не зная о RunController.
/// </summary>
public interface IRunExitService
{
    /// <summary>
    /// Просит закончить забег через портал: итоги, материалы на склад, сохранение — без подтверждения.
    /// Если код выполняется, выход произойдёт, когда запуск закончится (сам запуск не останавливается).
    /// false — выход сейчас невозможен (лагерь, забег уже закончен, идёт поражение).
    /// </summary>
    bool RequestExitThroughPortal();

    /// <summary>Выход через портал запрошен и ждёт конца запуска кода.</summary>
    bool IsExitPending { get; }
}
