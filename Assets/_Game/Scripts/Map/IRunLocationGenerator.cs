/// <summary>
/// Генератор места забега: по готовой карте выбирает тайл портала и точку появления игрока.
/// Детерминирован от seed (одинаковый seed и карта → одинаковое место).
///
/// Точка расширения. Сейчас рельеф строит TilemapGenerator.GenerateMap() (шаг 1 в Level), а генератор
/// места только читает карту. Level получает генератор в одном месте — Level.CreateRunLocationGenerator();
/// чтобы заменить генерацию локации забега, достаточно вернуть оттуда свою реализацию. Генератор, который
/// будет строить и сам рельеф, должен сделать это до/внутри Generate (например, заполнив карту, которую
/// отдаёт IMapDataProvider) и вернуть RunLocation — всё дальнейшее (объекты, стартовый набор, лагеря врагов,
/// головоломки, туман, камера, портал) берёт спавн и портал только из RunLocation.
/// </summary>
public interface IRunLocationGenerator
{
    RunLocation Generate(IMapDataProvider map, int seed);
}
